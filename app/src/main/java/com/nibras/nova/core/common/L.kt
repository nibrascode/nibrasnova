/**
 * Localized string lookup usable from anywhere (Compose, ViewModels, models).
 * Uses Android string resources (values, values-az, -tr, -ru, -ar); falls back to English
 * when no Context is available (e.g. JVM unit tests).
 */
object L {
    @Volatile
    private var appContext: Context? = null

    fun init(context: Context) {
        appContext = context.applicationContext
    }

    fun s(@StringRes id: Int, vararg args: Any?): String {
        val ctx = appContext
        if (ctx != null) {
            return runCatching {
                if (args.isEmpty()) ctx.getString(id) else ctx.getString(id, *args)
            }.getOrElse { fallback(id, args) }
        }
        return fallback(id, args)
    }

    private fun fallback(id: Int, args: Array<out Any?>): String {
        val en = EN[id] ?: return ""
        return if (args.isEmpty()) en else runCatching { String.format(en, *args) }.getOrDefault(en)
